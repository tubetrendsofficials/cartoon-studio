/* Cartoon Studio — original asset library registry (Phase 3).
   The catalogue lives in assets/manifest.json (generated by
   tools/build_assets.py from our own hand-drawn SVG artwork).
   This module loads the manifest once and provides a URL-keyed Image
   cache so the canvas renderer can draw SVG assets synchronously once
   they are loaded (and re-render when a load finishes). */

let manifestPromise = null;
let manifestCache = null;

/** Load (once) and return the asset manifest. */
export function loadAssets() {
  if (!manifestPromise) {
    manifestPromise = fetch('assets/manifest.json')
      .then((r) => {
        if (!r.ok) throw new Error('asset manifest failed to load (' + r.status + ')');
        return r.json();
      })
      .then((m) => { manifestCache = m; return m; });
  }
  return manifestPromise;
}

/** The manifest if it has already loaded, else null. */
export function assetsSync() {
  return manifestCache;
}

export function findCharacter(manifest, id) {
  return ((manifest && manifest.characters) || []).find((c) => c.id === id) || null;
}

export function findBackground(manifest, id) {
  return ((manifest && manifest.backgrounds) || []).find((b) => b.id === id) || null;
}

export function findProp(manifest, id) {
  return ((manifest && manifest.props) || []).find((p) => p.id === id) || null;
}

/** Manifest-relative file → fetchable URL. */
export function assetUrl(relFile) {
  return 'assets/' + relFile;
}

/** The manifest file for a layer's asset + pose (null when unknown). */
export function layerAssetFile(manifest, layer) {
  if (!manifest || !layer || !layer.assetId) return null;
  if (layer.kind === 'character') {
    const ch = findCharacter(manifest, layer.assetId);
    if (!ch) return null;
    const pose = ch.poses.find((p) => p.id === layer.poseId) || ch.poses[0];
    return pose ? pose.file : null;
  }
  if (layer.kind === 'background') {
    const bg = findBackground(manifest, layer.assetId);
    if (!bg) return null;
    /* Phase 10A: combo-pack backgrounds carry 2 scene variants; a layer
       may pin one of them via variantFile (validated against the pack). */
    if (layer.variantFile && Array.isArray(bg.variants)
        && bg.variants.some((v) => v.file === layer.variantFile)) {
      return layer.variantFile;
    }
    return bg.file;
  }
  if (layer.kind === 'prop') {
    const pr = findProp(manifest, layer.assetId);
    return pr ? pr.file : null;
  }
  return null;
}

/** Declared pixel size (viewBox) of an asset entry: {w, h}. */
export function assetNaturalSize(manifest, layer) {
  if (!manifest || !layer || !layer.assetId) return null;
  const entry = layer.kind === 'character' ? findCharacter(manifest, layer.assetId)
    : layer.kind === 'background' ? findBackground(manifest, layer.assetId)
    : layer.kind === 'prop' ? findProp(manifest, layer.assetId)
    : null;
  return entry ? { w: entry.w || 200, h: entry.h || 200 } : null;
}

/* ------------------------------ image cache ------------------------------ */

const imgCache = new Map(); // url -> { img, loaded, error }

/**
 * Synchronous peek at the image cache.
 * Returns { img, loaded } — when not yet loaded, loading is started and
 * `onLoad` (optional) fires once the image is ready (so callers can
 * re-render). Safe to call on every frame.
 */
export function peekAssetImage(relFile, onLoad) {
  const url = assetUrl(relFile);
  let entry = imgCache.get(url);
  if (!entry) {
    const img = new Image();
    entry = { img, loaded: false, error: false, waiters: [] };
    imgCache.set(url, entry);
    img.onload = () => {
      entry.loaded = true;
      const waiters = entry.waiters.splice(0);
      waiters.forEach((fn) => { try { fn(); } catch { /* ignore */ } });
    };
    img.onerror = () => { entry.error = true; };
    img.src = url;
  }
  if (!entry.loaded && !entry.error && onLoad) entry.waiters.push(onLoad);
  return entry;
}
